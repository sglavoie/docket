#!/usr/bin/env sh
#
# Print Casks/docket.rb for sglavoie/homebrew-tap. On macOS the cask installs the
# notarized Docket.app and links the docket it bundles as docket and dkt, so the
# app and the command line are one binary that one `brew upgrade` moves. On Linux
# it links the plain docket from the release tarball.
#
# Usage: homebrew_cask.sh VERSION MACOS_ZIP_SHA256 CHECKSUMS_TXT
#
# VERSION has no leading v. CHECKSUMS_TXT is GoReleaser's checksums.txt, which
# names the two Linux tarballs.

set -eu

if [ "$#" -ne 3 ]; then
	echo "usage: homebrew_cask.sh VERSION MACOS_ZIP_SHA256 CHECKSUMS_TXT" >&2
	exit 1
fi
version=$1 macos_sha=$2 checksums=$3

case "$version" in
v* | "")
	echo "VERSION has no leading v: '$version'" >&2
	exit 1
	;;
esac

require_sha() {
	if ! printf '%s' "$2" | grep -Eq '^[0-9a-f]{64}$'; then
		echo "no SHA-256 for $1" >&2
		exit 1
	fi
}

tarball_sha() {
	awk -v name="docket_${version}_linux_$1.tar.gz" '$2 == name { print $1 }' "$checksums"
}

linux_arm64_sha=$(tarball_sha arm64)
linux_amd64_sha=$(tarball_sha amd64)
require_sha "the macOS zip" "$macos_sha"
require_sha "docket_${version}_linux_arm64.tar.gz" "$linux_arm64_sha"
require_sha "docket_${version}_linux_amd64.tar.gz" "$linux_amd64_sha"

cat <<EOF
# This file is generated by docket's release workflow (scripts/homebrew_cask.sh). DO NOT EDIT.
cask "docket" do
  version "$version"

  on_macos do
    sha256 "$macos_sha"

    url "https://github.com/sglavoie/docket/releases/download/v#{version}/Docket_#{version}_macos_universal.zip"

    depends_on macos: :sonoma

    app "Docket.app"
    binary "#{appdir}/Docket.app/Contents/Resources/bin/docket"
    binary "#{appdir}/Docket.app/Contents/Resources/bin/docket", target: "dkt"

    # The app's own state only: the workspace under ~/.docket is the user's data.
    zap trash: [
      "~/Library/Application Support/io.github.sglavoie.docket",
      "~/Library/Preferences/io.github.sglavoie.docket.plist",
    ]
  end
  on_linux do
    on_arm do
      sha256 "$linux_arm64_sha"

      url "https://github.com/sglavoie/docket/releases/download/v#{version}/docket_#{version}_linux_arm64.tar.gz"
    end
    on_intel do
      sha256 "$linux_amd64_sha"

      url "https://github.com/sglavoie/docket/releases/download/v#{version}/docket_#{version}_linux_amd64.tar.gz"
    end

    binary "docket"
    binary "docket", target: "dkt"

    zap :not_required
  end

  name "Docket"
  desc "Local-first, keyboard-driven task manager for the terminal"
  homepage "https://github.com/sglavoie/docket"

  livecheck do
    url :url
    strategy :github_latest
  end

  bash_completion "completions/docket.bash"
  zsh_completion "completions/docket.zsh"
  fish_completion "completions/docket.fish"
  fish_completion "completions/dkt.fish"
end
EOF
